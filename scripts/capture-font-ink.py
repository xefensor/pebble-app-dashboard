#!/usr/bin/env python3
"""Measure stock Gothic through public drawing/Screenshot APIs in isolated Emery.

This QA app has a distinct UUID and no sources/actions. No firmware font pointer
or private structure is read. Run in the workspace recovery SDK environment.
"""
from pathlib import Path
import argparse, hashlib, json, os, struct, subprocess, sys, tempfile, threading, time, uuid

ROOT=Path(__file__).resolve().parents[1]
VERSION=json.loads((ROOT/'package.json').read_text())['version']
parser=argparse.ArgumentParser(description=__doc__)
parser.add_argument('--output',type=Path,default=ROOT/'docs/qa'/VERSION/'font-ink')
args=parser.parse_args()
output=args.output.resolve();output.mkdir(parents=True,exist_ok=True)
probe=ROOT/'scripts/font-probe'
subprocess.run(['pebble','build'],cwd=probe,check=True)
pbw=next((probe/'build').glob('*.pbw'))
sys.path.insert(0,str(ROOT.parent/'recovery-validation'))
os.environ.setdefault('PEBBLE_QA_STATE',tempfile.mkdtemp(prefix='dashboard-font-ink-'))
from pipe_emulator import connect
from pebble_tool.commands.install import ToolAppInstaller
from libpebble2.protocol.apps import AppRunState,AppRunStateStart
from libpebble2.services.appmessage import AppMessageService,Uint32
from libpebble2.services.screenshot import Screenshot
from PIL import Image

sha=lambda data:hashlib.sha256(data).hexdigest()
target=uuid.UUID('8191396b-dc27-4c2f-8664-432662fd522a')
points=list(range(32,384))+[0x2013,0x2014,0x2019,0x2026,0x2212,0x25af]
fonts=['GOTHIC_18_BOLD','GOTHIC_24_BOLD','GOTHIC_28_BOLD']
p=connect();service=AppMessageService(p);condition=threading.Condition();acks=set()
def ack(tid,app):
    if app==target:
        with condition:acks.add(tid);condition.notify_all()
service.register_handler('ack',ack)
ToolAppInstaller(p,str(pbw),quiet=True).install()
p.send_packet(AppRunState(data=AppRunStateStart(uuid=target)));time.sleep(.4)
measured=[];captures=[]
for font,name in enumerate(fonts):
    glyphs=[]
    for page in range(10):
        with condition:
            tid=service.send_message(target,{0:Uint32(font),1:Uint32(page)})
            assert condition.wait_for(lambda:tid in acks,timeout=6),'No probe ACK'
        time.sleep(.08)
        pixels=b''.join(Screenshot(p).grab_image());im=Image.frombytes('RGB',(200,228),pixels)
        path=output/f'{name.lower()}-{page}.png';im.save(path)
        captures.append({'file':path.name,'sha256':sha(path.read_bytes()),'rgbSha256':sha(pixels),'nativePixelsModified':False})
        for cell in range(36):
            index=page*36+cell
            if index>=len(points):break
            x=cell%6*33;y=cell//6*38
            ink=[dy for dy in range(38) for dx in range(33) if im.getpixel((x+dx,y+dy))!=(255,255,255)]
            glyphs.append({'codepoint':points[index],'top':min(ink) if ink else 255,'bottom':max(ink) if ink else 0})
    assert len(glyphs)==len(points)
    measured.append({'font':name,'glyphs':glyphs})
service.shutdown()

# Custom numeric roles retain exact SDK PFO bounds from the production pack.
from font_ink_data import pfo_metrics

package=json.loads((ROOT/'package.json').read_text());packed=(ROOT/'build/emery/app_resources.pbpack').read_bytes();clock={}
for i,item in enumerate(package['pebble']['resources']['media']):
    if not item['name'].startswith('FONT_CLOCK_'):continue
    _,offset,size,_=struct.unpack_from('<4I',packed,12+i*16)
    clock[int(item['name'].split('_')[-1])]=pfo_metrics(packed[4108+offset:4108+offset+size])
clock_points=sorted(set.intersection(*(set(rows) for rows in clock.values())))
lines=['// Generated by scripts/capture-font-ink.py; Emery SDK 4.33.1. Do not edit.',
       '// See docs/qa/'+VERSION+'/font-ink/report.json for native grid captures.',
       '#pragma once','#define DB_GOTHIC_GLYPH_COUNT '+str(len(points)),
       'static const uint16_t db_gothic_extra[]={0x2013,0x2014,0x2019,0x2026,0x2212,0x25af};',
       'static const DbGlyphInk db_gothic_ink[3][DB_GOTHIC_GLYPH_COUNT]={']
for font in measured:
    lines.append('  { // '+font['font'])
    for start in range(0,len(points),12):
        lines.append('    '+','.join('{%d,%d}'%(g['top'],g['bottom']) for g in font['glyphs'][start:start+12])+',')
    lines.append('  },')
lines+=['};','static const DbClockGlyphInk db_clock_ink[]={']
for code in clock_points:
    lines.append('  {%d,{%s}},'%(code,','.join('{%d,%d}'%(clock[point][code]['top'],clock[point][code]['bottom']) for point in (20,24,26,32,40))))
lines+=['};','']
header='\n'.join(lines);(output/'reference-font-ink.h').write_text(header)
report={'sdk':'4.33.1','platform':'emery','scope':'Actual public SDK drawing and unchanged Screenshot-service PNGs; one glyph per33x38cell. Latin32..383 plus6punctuation/fallback glyphs. This is native-emulator evidence, not a physical watch.',
        'probePbwSha256':sha(pbw.read_bytes()),'probeSourceSha256':sha((probe/'src/c/main.c').read_bytes()),
        'generatedHeaderSha256':sha(header.encode()),'productionResourcesSha256':sha(packed),
        'fonts':measured,'clockMetricsSource':'Exact production SDK PFO glyph bounds, not font point names','captures':captures}
(output/'report.json').write_text(json.dumps(report,indent=2)+'\n')
print('Measured',len(points),'glyphs per Gothic role; generated study',output/'reference-font-ink.h')
